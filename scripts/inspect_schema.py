        "| `program_length` | float | Total program duration in weeks | Integer values 1–18; ~0.003% null |",
        "| `time_per_workout` | float | Expected workout duration in minutes | Range 10–180; no nulls |",
        "| `week` | float | Week number within the program | 1-indexed; range 1–18 |",
        "| `day` | float | Day number within the week | 1-indexed; range 1–10 |",
        "| `number_of_exercises` | float | Exercises scheduled for this day | Range 1–24 |",
        "| `exercise_name` | str | Name of the exercise | 3,213 unique names |",
        "| `sets` | float | Number of sets prescribed | Range 1–30; median 3 |",
        "| `reps` | float | Reps **or** negative seconds for time-based exercises | Negative = time-based: e.g. -180 = 180 s. Use `abs(reps)` + `is_time_based` flag |",
        "| `intensity` | float | Perceived intensity on 0–10 scale | Integer values 0–10; no nulls |",
        "| `created` | str | Program creation timestamp | Format: `YYYY-MM-DD HH:MM:SS` |",
        "| `last_edit` | str | Last edit timestamp | ~0.01% null |",
        "",
        "### Missing values",
        "",
        "| Column | Null count | Null % |",
        "|---|---|---|",
        null_table(detail),
