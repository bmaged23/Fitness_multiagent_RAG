OUT_PATH = DATA_SCHEMA_DIR / "data_dictionary.md"


def safe_parse_list(val):
    try:
        result = ast.literal_eval(val)
        return result if isinstance(result, list) else [result]
    except Exception:
        return [val] if pd.notna(val) else []


def null_table(df: pd.DataFrame) -> str:
    rows = []
    for col in df.columns:
        n = df[col].isnull().sum()
        pct = n / len(df) * 100
        rows.append(f"| `{col}` | {n:,} | {pct:.2f}% |")
    return "\n".join(rows)


def numeric_stats(df: pd.DataFrame, cols: list) -> str:
    desc = df[cols].describe().round(2)
    lines = ["| stat | " + " | ".join(cols) + " |"]
    lines.append("|---|" + "---|" * len(cols))
    for stat in desc.index:
        vals = " | ".join(str(desc.loc[stat, c]) for c in cols)
        lines.append(f"| {stat} | {vals} |")
    return "\n".join(lines)


def value_counts_table(series: pd.Series, top_n: int = 20) -> str:
    vc = series.value_counts(dropna=False).head(top_n)
    rows = []
    total = len(series)
    for val, cnt in vc.items():
        pct = cnt / total * 100
        rows.append(f"| `{val}` | {cnt:,} | {pct:.1f}% |")
    return "\n".join(rows)


def list_col_counts(series: pd.Series) -> str:
    counts = Counter(v for cell in series for v in safe_parse_list(cell))
    rows = []
    total_programs = len(series)
    for val, cnt in counts.most_common():
        pct = cnt / total_programs * 100
        rows.append(f"| `{val}` | {cnt:,} | {pct:.1f}% |")
    return "\n".join(rows)


